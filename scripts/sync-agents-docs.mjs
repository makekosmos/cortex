/*
 * sync-agents-docs.mjs
 *
 * Источник правды для всех инструкций агентам и человеку — `docs-site/`.
 * Этот скрипт читает оттуда соответствующие markdown-файлы и регенерирует:
 *
 *   - AGENTS.md      (корень)        — auto-context для всех агентов
 *   - CLAUDE.md      (корень)        — auto-context для Claude Code
 *   - mobile/delphi/AGENTS.md        — Android Delphi правила
 *   - crates/ark-core/AGENTS.md      — ark-core правила
 *   - services/<name>/AGENTS.md      — per-service правила (на данный момент таких нет; usage-tracker заморожен в legacy/)
 *   - docs-site/public/llms.txt      — полный inline-текст для агентов через WebFetch
 *
 * Все сгенерированные файлы помечены меткой `<!-- AUTO-GENERATED: do not edit -->`.
 * Правь только под `docs-site/` и запускай `bun run docs:sync`.
 */

import { readFile, writeFile, mkdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import { spawnSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const DOCS = path.join(ROOT, "docs-site");

const MARK =
  "<!-- AUTO-GENERATED by scripts/sync-agents-docs.mjs — do not edit; правь docs-site/ -->";

const GENERATED_CONTEXT_BUDGETS = {
  "AGENTS.md": { maxLines: 220, maxBytes: 32_000 },
  "CLAUDE.md": { maxLines: 220, maxBytes: 32_000 },
  "mobile/delphi/AGENTS.md": { maxLines: 180, maxBytes: 24_000 },
  "crates/ark-core/AGENTS.md": { maxLines: 180, maxBytes: 24_000 },
};

// ─────────────────────────────────────────────────────────────────────────────
// utils
// ─────────────────────────────────────────────────────────────────────────────

async function readDoc(rel) {
  const p = path.join(DOCS, rel);
  if (!existsSync(p)) {
    console.warn(`[skip] нет файла: ${rel}`);
    return "";
  }
  return await readFile(p, "utf8");
}

function stripFrontmatter(md) {
  if (!md.startsWith("---")) return md;
  const end = md.indexOf("\n---", 3);
  if (end === -1) return md;
  return md.slice(end + 4).replace(/^\s*\n/, "");
}

function rewriteLinks(md, _siteOrigin = "/") {
  // Превращаем относительные ссылки на страницы сайта в указание пути.
  // `/concepts/architecture` → `docs-site/concepts/architecture.md`
  return md.replace(/\]\((\/[a-z0-9\-/]+)\)/gi, (_, p) => {
    if (p.startsWith("//") || p.startsWith("http")) return `](${p})`;
    // Не трогаем якоря и явные .md
    if (p.endsWith(".md")) return `](docs-site${p})`;
    const segs = p.split("#");
    const route = segs[0].replace(/\/$/, "");
    const hash = segs[1] ? `#${segs[1]}` : "";
    return `](docs-site${route}.md${hash})`;
  });
}

async function write(rel, content) {
  assertGeneratedContextBudget(rel, content);
  const full = path.join(ROOT, rel);
  await mkdir(path.dirname(full), { recursive: true });
  await writeFile(full, content, "utf8");
  console.log(`  ✓ ${rel}`);
}

function assertGeneratedContextBudget(rel, content) {
  const budget = GENERATED_CONTEXT_BUDGETS[rel];
  if (!budget) return;

  const lineCount = content.split(/\r?\n/).length;
  const byteCount = Buffer.byteLength(content, "utf8");
  if (lineCount <= budget.maxLines && byteCount <= budget.maxBytes) return;

  throw new Error(
    `${rel} exceeds context budget: ${lineCount}/${budget.maxLines} lines, ${byteCount}/${budget.maxBytes} bytes. ` +
      "Move detail into docs-site/ and keep the generated root context as pointers.",
  );
}

// ─────────────────────────────────────────────────────────────────────────────
// шаблоны
// ─────────────────────────────────────────────────────────────────────────────

function header(title, extraLines = []) {
  return [
    `# ${title}`,
    "",
    MARK,
    "",
    "Источник правды — `docs-site/`. Этот файл собирается автоматически из",
    "соответствующих страниц документации скриптом `scripts/sync-agents-docs.mjs`.",
    "Открой собранный сайт (`bun run docs:dev`, http://localhost:5173/) для",
    "удобного чтения.",
    ...extraLines,
    "",
    "---",
    "",
  ].join("\n");
}

