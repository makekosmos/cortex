#!/usr/bin/env node
/*
 * sync-agents-docs.mjs
 *
 * Источник правды для всех инструкций агентам и человеку — `docs-site/`.
 * Этот скрипт читает оттуда соответствующие markdown-файлы и регенерирует:
 *
 *   - AGENTS.md      (корень)        — auto-context для всех агентов
 *   - CLAUDE.md      (корень)        — auto-context для Claude Code
 *   - apps/<name>/AGENTS.md          — per-app правила
 *   - packages/<name>/AGENTS.md      — per-package правила (только ark-core)
 *   - services/<name>/AGENTS.md      — per-service правила (только usage-tracker)
 *   - docs-site/public/llms.txt      — полный inline-текст для агентов через WebFetch
 *
 * Все сгенерированные файлы помечены меткой `<!-- AUTO-GENERATED: do not edit -->`.
 * Правь только под `docs-site/` и запускай `bun run docs:sync`.
 */

import { readFile, writeFile, mkdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const DOCS = path.join(ROOT, "docs-site");

const MARK = "<!-- AUTO-GENERATED by scripts/sync-agents-docs.mjs — do not edit; правь docs-site/ -->";

// ─────────────────────────────────────────────────────────────────────────────
// utils
// ─────────────────────────────────────────────────────────────────────────────

async function readDoc(rel) {
  const p = path.join(DOCS, rel);
  if (!existsSync(p)) {
    console.warn(`[skip] нет файла: ${rel}`);
    return "";
  }
  return await readFile(p, "utf8");
}

function stripFrontmatter(md) {
  if (!md.startsWith("---")) return md;
  const end = md.indexOf("\n---", 3);
  if (end === -1) return md;
  return md.slice(end + 4).replace(/^\s*\n/, "");
}

function rewriteLinks(md, siteOrigin = "/") {
  // Превращаем относительные ссылки на страницы сайта в указание пути.
  // `/concepts/architecture` → `docs-site/concepts/architecture.md`
  return md.replace(/\]\((\/[a-z0-9\-/]+)\)/gi, (_, p) => {
    if (p.startsWith("//") || p.startsWith("http")) return `](${p})`;
    // Не трогаем якоря и явные .md
    if (p.endsWith(".md")) return `](docs-site${p})`;
    const segs = p.split("#");
    const route = segs[0].replace(/\/$/, "");
    const hash = segs[1] ? `#${segs[1]}` : "";
    return `](docs-site${route}.md${hash})`;
  });
}

async function write(rel, content) {
  const full = path.join(ROOT, rel);
  await mkdir(path.dirname(full), { recursive: true });
  await writeFile(full, content, "utf8");
  console.log(`  ✓ ${rel}`);
}

// ─────────────────────────────────────────────────────────────────────────────
// шаблоны
// ─────────────────────────────────────────────────────────────────────────────

function header(title, extraLines = []) {
  return [
    `# ${title}`,
    "",
    MARK,
    "",
    "Источник правды — `docs-site/`. Этот файл собирается автоматически из",
    "соответствующих страниц документации скриптом `scripts/sync-agents-docs.mjs`.",
    "Открой собранный сайт (`bun run docs:dev`, http://localhost:5173/) для",
    "удобного чтения.",
    ...extraLines,
    "",
    "---",
    "",
  ].join("\n");
}

// Slug якоря: совпадает с правилами VitePress/GitHub для русских заголовков —
// нижний регистр, пробелы → `-`, не-буквенно-цифровые отброшены.
function slugify(s) {
  return s
    .toLowerCase()
    .trim()
    .replace(/[^\p{L}\p{N}\s-]/gu, "")
    .replace(/\s+/g, "-");
}

function toc(labels) {
  const lines = ["## Содержание", ""];
  labels.forEach((l, i) => {
    lines.push(`${i + 1}. [${l}](#${slugify(l)})`);
  });
  lines.push("", "");
  return lines.join("\n");
}

function block(label, body) {
  return [`## ${label}`, "", stripFrontmatter(body).trim(), ""].join("\n");
}

// Разделитель между крупными секциями — пустая строка + `---` + пустая строка.
function joinBlocks(...blocks) {
  return blocks.filter(Boolean).join("\n---\n\n");
}

// ─────────────────────────────────────────────────────────────────────────────
// корневой AGENTS.md / CLAUDE.md
// ─────────────────────────────────────────────────────────────────────────────

async function buildRootAgents() {
  const agentIndex = await readDoc("agents/index.md");
  const forbidden = await readDoc("agents/forbidden.md");
  const checklists = await readDoc("agents/checklists.md");
  const docsMaintenance = await readDoc("agents/docs-maintenance.md");
  const rules = await readDoc("reference/rules.md");
  const proofLoop = await readDoc("concepts/proof-loop.md");

  const agentsLabels = [
    "Старт",
    "Запреты",
    "Чек-листы",
    "Поддержка документации",
    "Сжатые правила",
    "Proof loop",
  ];

  const agentsBody =
    header("AGENTS.md — Kepler") +
    "\n" +
    toc(agentsLabels) +
    "---\n\n" +
    joinBlocks(
      block("Старт", rewriteLinks(agentIndex)),
      block("Запреты", rewriteLinks(forbidden)),
      block("Чек-листы", rewriteLinks(checklists)),
      block("Поддержка документации", rewriteLinks(docsMaintenance)),
      block("Сжатые правила", rewriteLinks(rules)),
      block("Proof loop", rewriteLinks(proofLoop)),
    );

  await write("AGENTS.md", agentsBody);

  const claudeHeader = [
    "# CLAUDE.md",
    "",
    MARK,
    "",
    "Auto-generated файл с контекстом работы над Kepler для Claude Code.",
    "Источник — `docs-site/`, регенерация — `bun run docs:sync`. Полный набор",
    "правил продублирован в `AGENTS.md` (Claude Code читает оба).",
    "",
    "См. также:",
    "- `docs-site/agents/index.md` — старт",
    "- `docs-site/agents/forbidden.md` — нерушимые запреты",
    "- `docs-site/agents/checklists.md` — чек-листы по областям",
    "- `docs-site/agents/docs-maintenance.md` — поддержка документации в актуальном состоянии",
    "- `docs-site/agents/spec-templates.md` — шаблоны spec.md",
    "- `docs-site/concepts/` — концепты архитектуры",
    "- `docs-site/reference/rules.md` — сжатый чек-лист правил",
    "",
    "---",
    "",
  ].join("\n");

  const claudeLabels = ["Старт", "Запреты", "Чек-листы", "Поддержка документации"];

  await write(
    "CLAUDE.md",
    claudeHeader +
      "\n" +
      toc(claudeLabels) +
      "---\n\n" +
      joinBlocks(
        block("Старт", rewriteLinks(agentIndex)),
        block("Запреты", rewriteLinks(forbidden)),
        block("Чек-листы", rewriteLinks(checklists)),
        block("Поддержка документации", rewriteLinks(docsMaintenance)),
      ),
  );
}

// ─────────────────────────────────────────────────────────────────────────────
// per-app / per-package / per-service AGENTS.md
// ─────────────────────────────────────────────────────────────────────────────

const TARGETS = [
  // root-level apps
  { dest: "apps/eden/AGENTS.md", src: "apps/eden.md", title: "Eden" },
  { dest: "apps/delphi/AGENTS.md", src: "apps/delphi.md", title: "Delphi" },
  { dest: "apps/arrancador/AGENTS.md", src: "apps/arrancador.md", title: "Arrancador" },
  { dest: "apps/dashboard/AGENTS.md", src: "apps/dashboard.md", title: "Dashboard" },
  // nested workspaces
  { dest: "apps/eden/ts/AGENTS.md", src: "apps/eden.md", title: "Eden — TS workspace" },
  { dest: "apps/delphi/kotlin/AGENTS.md", src: "apps/delphi.md", title: "Delphi — Kotlin workspace" },
  // packages / services
  { dest: "packages/ark-core/AGENTS.md", src: "packages/ark-core.md", title: "ark-core" },
  { dest: "services/usage-tracker/AGENTS.md", src: "services/usage-tracker.md", title: "usage-tracker" },
];

// TL;DR версия `reference/rules.md` — 5-7 строк по ключевым правилам.
// Полный текст всегда доступен в корневом `AGENTS.md` и `docs-site/reference/rules.md`.
const RULES_TLDR = [
  "## Сжатые правила репозитория (TL;DR)",
  "",
  "- **ARK writes** — только через `@kepler/ark` (TS) или `ark_core::db` (Rust). Прямые SQL writes в `objects` / `object_types` / `object_links` / `tracked_apps` / `usage_sessions` / `usage_events` / `sync_kv` запрещены.",
  "- **Read-only SQL** — renderer никогда не открывает SQLite; read-only fallback в Electron main отделён от write paths и не ходит в user DB из тестов.",
  "- **Тестовая изоляция** — только `.tmp`, `.e2e`, `.agent/tasks/<TASK_ID>/smoke/` или OS temp. User data dir в автотестах — отказ на ревью.",
  "- **Proof loop** — substantial-правки идут через `.agent/tasks/<DATE>-<slug>/`: spec → реализация → evidence → (problems → fix → reverify). Каждый AC = `PASS`.",
  "- **Sync state** — direct writers в синхронизируемые таблицы обязаны вызывать `ark_core::db::bump_sync_version_vector`.",
  "- **Tooling** — `bun run ark:guard:writes` перед PR в data-слой; `bun run ark:smoke` перед нетривиальным PR.",
  "",
  "Полный текст: [`AGENTS.md`](../../AGENTS.md#сжатые-правила) и `docs-site/reference/rules.md`.",
  "",
].join("\n");

async function buildPerAreaAgents() {
  const forbidden = await readDoc("agents/forbidden.md");

  for (const t of TARGETS) {
    const main = await readDoc(t.src);
    if (!main) continue;

    // Глубина пути для ссылки на корневой AGENTS.md из per-area файла.
    const depth = t.dest.split("/").length - 1;
    const upPath = "../".repeat(depth) + "AGENTS.md";
    const tldr = RULES_TLDR.replace("../../AGENTS.md", upPath);

    const body =
      header(`AGENTS.md — ${t.title}`, [
        "",
        `Полная страница: \`docs-site/${t.src}\`.`,
      ]) +
      joinBlocks(
        block(`Контекст: ${t.title}`, rewriteLinks(main)),
        block("Общие запреты (повторение)", rewriteLinks(forbidden)),
        tldr,
      );

    await write(t.dest, body);
  }
}

// ─────────────────────────────────────────────────────────────────────────────
// llms.txt — полный inline текст
// ─────────────────────────────────────────────────────────────────────────────

async function buildLlmsTxt() {
  const sections = [
    { title: "0. О документе", file: "agents/index.md" },
    { title: "1. Архитектура", file: "concepts/architecture.md" },
    { title: "2. Модель данных ARK", file: "concepts/ark-objects.md" },
    { title: "3. Синхронизация", file: "concepts/sync.md" },
    { title: "4. Граница записи в ARK", file: "concepts/write-boundary.md" },
    { title: "5. Read-only SQL", file: "concepts/readonly-sql.md" },
    { title: "6. Proof loop", file: "concepts/proof-loop.md" },
    { title: "7. Изоляция тестовых БД", file: "concepts/test-isolation.md" },
    { title: "8. Запреты", file: "agents/forbidden.md" },
    { title: "9. Чек-листы", file: "agents/checklists.md" },
    { title: "10. Шаблоны спецификаций", file: "agents/spec-templates.md" },
    { title: "10.1. Поддержка документации", file: "agents/docs-maintenance.md" },
    { title: "11. Сжатые правила", file: "reference/rules.md" },
    { title: "12. Smoke-матрица", file: "reference/smoke-matrix.md" },
    { title: "13. Глоссарий", file: "reference/glossary.md" },
    { title: "14. Команды", file: "reference/commands.md" },
    { title: "15. Решения (ADR)", file: "reference/decisions.md" },
  ];

  const contents = ["## Contents", ""];
  sections.forEach((s) => {
    contents.push(`${s.title} — section ## (источник: docs-site/${s.file})`);
  });
  contents.push("");

  const head = [
    "# Kepler — llms.txt",
    "",
    "Полный inline-текст правил и контекста репозитория Kepler.",
    "Источник правды — docs-site/. Этот файл генерируется скриптом scripts/sync-agents-docs.mjs.",
    "",
    "Структура: каждый раздел — отдельный концепт или область. Читай по порядку для полной картины.",
    "",
    "---",
    "",
    contents.join("\n"),
    "---",
    "",
  ].join("\n");

  let body = head;
  for (const s of sections) {
    const md = await readDoc(s.file);
    if (!md) continue;
    body += `\n## ${s.title}\n\n`;
    body += rewriteLinks(stripFrontmatter(md)).trim();
    body += "\n\n";
  }

  // llms.txt живёт в public/ — VitePress положит его в корень собранного сайта
  await write("docs-site/public/llms.txt", body);
}

// ─────────────────────────────────────────────────────────────────────────────
// main
// ─────────────────────────────────────────────────────────────────────────────

async function main() {
  console.log("→ sync agents docs");
  await buildRootAgents();
  await buildPerAreaAgents();
  await buildLlmsTxt();
  console.log("done.");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
