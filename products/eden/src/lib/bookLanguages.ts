export function normalizeBookLanguage(value: unknown): string {
  const original = String(value ?? "").trim();
  const key = original.toLocaleLowerCase("ru-RU").replaceAll("_", "-");
  if (!key) return "";
  return LANGUAGE_ALIASES[key] ?? LANGUAGE_ALIASES[key.split("-")[0] ?? ""] ?? original;
}

export function isBookLanguageField(field: { id: string; options?: readonly string[] }): boolean {
  return (
    field.id === "language" &&
    field.options?.length === BOOK_LANGUAGE_OPTIONS.length &&
    BOOK_LANGUAGE_OPTIONS.every((option, index) => field.options?.[index] === option)
  );
}
